// Package lock reads and writes trellis.lock: everything that would
// otherwise make compilation depend on the network or on time (package
// versions, image digests, SSH keys fetched from GitHub, ejected template
// bases). Compilation is a pure function of trellis.yml + trellis.lock.
package lock

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"

	"go.yaml.in/yaml/v3"
)

const FileName = "trellis.lock"

type Lock struct {
	Version int `yaml:"version"`
	// MovedOS rejects the old `os:` key, which moved to trellis.yml.
	MovedOS string `yaml:"os,omitempty"`
	// AptSnapshot pins the Ubuntu archive to snapshot.ubuntu.com at this
	// timestamp (e.g. 20261120T000000Z).
	AptSnapshot string `yaml:"apt_snapshot,omitempty"`
	// Packages maps apt package name → exact version.
	Packages map[string]string `yaml:"packages,omitempty"`
	// Tools pins downloaded binaries (wp-cli, composer).
	Tools map[string]Tool `yaml:"tools,omitempty"`
	// SSHKeys maps a key reference (github:<user>) → public keys.
	SSHKeys map[string][]string `yaml:"ssh_keys,omitempty"`
	// Ejected records the built-in template hash each ejected file was
	// copied from, so upgrades can warn when upstream changed.
	Ejected map[string]Ejected `yaml:"ejected,omitempty"`
}

type Tool struct {
	Version string `yaml:"version"`
	SHA256  string `yaml:"sha256,omitempty"`
}

type Ejected struct {
	Base   string `yaml:"base"`   // trellis-cli version
	SHA256 string `yaml:"sha256"` // sha256 of the built-in template at eject time
}

// New returns an empty lock.
func New() *Lock { return &Lock{Version: 1} }

// Load reads path. A missing file is an empty lock.
func Load(path string) (*Lock, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return New(), nil
	}
	if err != nil {
		return nil, err
	}
	return Parse(b)
}

func Parse(b []byte) (*Lock, error) {
	l := New()
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(l); err != nil {
		return nil, fmt.Errorf("trellis.lock: %w", err)
	}
	if l.Version != 1 {
		return nil, fmt.Errorf("trellis.lock: unsupported version %d", l.Version)
	}
	if l.MovedOS != "" {
		return nil, fmt.Errorf("trellis.lock: os moved to trellis.yml: remove it here and set `os: %s` in defaults (or per environment)", l.MovedOS)
	}
	return l, nil
}

// Marshal encodes the lock deterministically (maps are sorted by yaml.v3).
func (l *Lock) Marshal() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("# Generated by `trellis converge lock`. Commit it; don't edit it.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(l); err != nil {
		return nil, err
	}
	return buf.Bytes(), enc.Close()
}

func (l *Lock) Save(path string) error {
	b, err := l.Marshal()
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}
